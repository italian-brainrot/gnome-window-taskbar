#!/usr/bin/env bash
# Reload the fork's code into the running GNOME Shell (needs scripts/dev-setup.sh
# once, plus one session restart to make the shell scan the dev loader).
#
#   scripts/hotreload.sh          # code + stylesheet reload
#   scripts/hotreload.sh --prefs  # also restart the prefs service process
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

DEV_UUID=windowtaskbar-dev@local
BUILD=build/dev
CURRENT=$BUILD/current

HOST_EXEC() {
    if command -v distrobox-host-exec >/dev/null 2>&1; then
        distrobox-host-exec "$@"
    else
        "$@"
    fi
}

HOST_HOME=${HOST_HOME:-$(distrobox-host-exec sh -c 'getent passwd "$(id -un)"' | cut -d: -f6)}
SHIM_DIR="$HOST_HOME/.local/share/gnome-shell/extensions/$DEV_UUID"

if [[ ! -f $SHIM_DIR/extension.js ]]; then
    echo "no dev loader installed in $SHIM_DIR - run scripts/dev-setup.sh first" >&2
    exit 1
fi

start_ts=$EPOCHSECONDS
previous=$(cat "$CURRENT" 2>/dev/null || echo 0)
iter=$((previous + 1))

mkdir -p "$BUILD"
rm -rf "$BUILD/iter$iter"
cp -a src "$BUILD/iter$iter"
python3 dev/rename_classes.py "$BUILD/iter$iter" "$iter" >/dev/null

# Dev-only inspector: the entry module is replaced by a wrapper that imports the
# fork's own entry module and attaches the probe. Only the iteration build gets
# this - the shipped tree (src/) stays as it is.
cp dev/probe.js "$BUILD/iter$iter/devProbe.js"
node --check dev/probe.js 2>/dev/null || command -v node >/dev/null || true
mv "$BUILD/iter$iter/extension.js" "$BUILD/iter$iter/taskbarExtension.js"
cat >"$BUILD/iter$iter/extension.js" <<EOF
// Generated by scripts/hotreload.sh - do not edit.
// The fork's entry module keeps the named exports: other fork modules import
// them from './extension.js', so 'export *' re-exports them from the wrapper.
import Fork from './taskbarExtension.js';
import {attach} from './devProbe.js';
export * from './taskbarExtension.js';

class WindowTaskbarDevIter$iter extends Fork {
    async enable() {
        await super.enable();
        this._probeRelease = attach(this);
    }

    disable() {
        this._probeRelease?.();
        this._probeRelease = null;
        super.disable();
    }
}

export default WindowTaskbarDevIter$iter;
EOF
HOST_EXEC glib-compile-schemas --strict "$PWD/$BUILD/iter$iter/schemas"
echo "$iter" >"$CURRENT"

# The loader's own directory keeps what the shell/daemon reads directly: the
# stylesheet (loaded per extension dir) and the prefs (loaded by the service).
cp src/stylesheet.css "$SHIM_DIR/"
cp src/prefs.js "$SHIM_DIR/"
rm -rf "$SHIM_DIR/settings" "$SHIM_DIR/schemas"
cp -r src/settings src/schemas "$SHIM_DIR/"
HOST_EXEC glib-compile-schemas --strict "$SHIM_DIR/schemas"

# The probe answers a 'dump.request' file: drop any previous answer and ask
# only the *new* instance (touch after the disable, so the outgoing instance
# cannot answer it).
rm -f "$BUILD/dump.json"
HOST_EXEC gnome-extensions disable "$DEV_UUID" >/dev/null 2>&1 || true
touch "$BUILD/dump.request"
if ! HOST_EXEC gnome-extensions enable "$DEV_UUID"; then
    echo "could not enable $DEV_UUID: the shell only scans extension directories" >&2
    echo "at session start - log out and back in once (after dev-setup.sh)." >&2
    exit 1
fi

if [[ ${1:-} == --prefs ]]; then
    # The prefs service is D-Bus activated: killing it drops its module cache,
    # the next 'Preferences' request starts it again with the new prefs code.
    HOST_EXEC pkill -TERM -f 'gjs -m /usr/share/gnome-shell/org.gnome.Shell.Extensions' || true
fi

# prune by iteration number, not mtime: 'cp -a' preserves the source directory's
# timestamps, so a freshly copied iteration does not sort as the newest one
ls -1 "$BUILD" | grep -E '^iter[0-9]+$' | sort -V | head -n -3 | sed "s#^#$BUILD/#" | xargs -r rm -rf

# The dump is answered from the shell's own enable path, which is asynchronous:
# give it a moment before deciding it did not come.
for _ in {1..20}; do
    [[ -f $BUILD/dump.json ]] && break
    sleep 0.25
done
rm -f "$BUILD/dump.request"   # the new instance already answered it during enable

# A wrong size request is not a warning the shell lives with: Clutter asserts
# and takes the session down with it (that is how this shell crashed once
# already). Check the log for those complaints, and unload the dev build again
# when this iteration made the shell unhappy.
complaints=$({ HOST_EXEC journalctl --user --no-pager --since "@$start_ts" -q || true; } \
    | grep -E 'ClutterBoxLayout|invalid or out of range|clutter_actor_insert_child_at_index' || true)
if [[ -n $complaints ]]; then
    printf 'the shell complained about this build, disabling %s again:\n%%s\n' \
        "$DEV_UUID" "$complaints" >&2
    ${ HOST_EXEC gnome-extensions disable "$DEV_UUID"; } || true
    echo "iter$iter" > "$BUILD/FAILED"
    exit 1
fi

if [[ -f $BUILD/dump.json ]]; then
    echo "reloaded iter$iter, dumped state in build/dev/dump.json"
else
    echo "reloaded iter$iter (no dump yet - the shell did not report one)"
fi
